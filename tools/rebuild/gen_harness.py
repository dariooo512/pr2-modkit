#!/usr/bin/env python3
"""Generate (and optionally run) an execution-oracle test for a rebuilt function:
the ORIGINAL machine code and your rebuild run side by side on random inputs, and every
result is compared (method A).

    python gen_harness.py 0x0041C6F0 --size 74                       # write the harness
    python gen_harness.py 0x0041C6F0 --size 74 --run --source my/0x0041C6F0.cpp

For a function that classify.py calls self-contained (no globals, no calls, no x87) and
that takes no pointer arguments. The harness
  - reads the function's original bytes from the exe AT RUN TIME (the generated file
    holds only the file offset, the length and a hash, never the bytes), copies them
    into executable memory and checks the hash;
  - fills a large `this` buffer (passed in ECX) and the scalar stack arguments with
    random values, calls the original and your sub_<VA> on identical copies with the
    convention classify.py found (__fastcall(ecx, edx, ...) or __cdecl), compares the return
    value (by offset when it points into the object) and the whole object afterwards;
  - prints `tested=N fails=M`; exit 0 = PASS, 1 = mismatches, 3 = a fault (the function
    dereferences memory the oracle cannot supply: it needs a real-state test instead).

A pass on random state is evidence, not proof: functions that passed this way have still
crashed the game when patched in together (README). Byte identity (build.py) is the
stronger gate. Output goes to --out-dir (default _build/rebuild/harness).
"""
import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import classify  # noqa: E402
import pe_image  # noqa: E402
from pe_image import kit_paths  # noqa: E402

TEMPLATE = r'''/* Generated by gen_harness.py: execution oracle for sub_{va}.
 * Usage: harness.exe <path of the exe the function comes from>
 * The original bytes are read from that file at offset 0x{off:X} ({size} bytes). */
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

extern "C" {decl_ret} {cc} sub_{va}({params});
extern "C" __declspec(dllimport) void* __stdcall VirtualAlloc(void*, unsigned long,
                                                               unsigned long, unsigned long);
typedef {decl_ret} ({cc} *fn_t)({params});

#define FILE_OFF 0x{off:X}ul
#define FN_SIZE {size}u
#define FN_FNV1A 0x{fnv:08X}u
#define THIS_SZ 0x{this_sz:X}
#define ITERS {iters}L

static unsigned int rs = 0x12345678u;
static unsigned int rnd() {{ rs ^= rs << 13; rs ^= rs >> 17; rs ^= rs << 5; return rs; }}

int main(int argc, char** argv) {{
    if (argc < 2) {{ printf("usage: %s <exe>\n", argv[0]); return 2; }}
    FILE* f = fopen(argv[1], "rb");
    if (!f) {{ printf("cannot open %s\n", argv[1]); return 2; }}
    unsigned char* mem = (unsigned char*)VirtualAlloc(0, FN_SIZE, 0x3000u, 0x40u);
    if (fseek(f, (long)FILE_OFF, SEEK_SET) != 0 || fread(mem, 1, FN_SIZE, f) != FN_SIZE) {{
        printf("cannot read the function from %s\n", argv[1]); return 2;
    }}
    fclose(f);
    unsigned int h = 2166136261u;
    for (unsigned i = 0; i < FN_SIZE; ++i) {{ h ^= mem[i]; h *= 16777619u; }}
    if (h != FN_FNV1A) {{ printf("the bytes at 0x%lX are not the expected function (other exe?)\n", FILE_OFF); return 2; }}
    fn_t orig = (fn_t)mem;

    unsigned char* a = (unsigned char*)malloc(THIS_SZ);
    unsigned char* b = (unsigned char*)malloc(THIS_SZ);
    unsigned int* a4 = (unsigned int*)a; unsigned int* b4 = (unsigned int*)b;
    unsigned long tested = 0, fails = 0;
    for (long iter = 0; iter < ITERS; ++iter) {{
        for (int i = 0; i < THIS_SZ / 4; ++i) {{ unsigned int v = rnd(); a4[i] = v; b4[i] = v; }}
        {argset}
        int bad = 0;
        __try {{
            {call_o}orig({args_o});
            {call_r}sub_{va}({args_r});
            if (memcmp(a, b, THIS_SZ) != 0) bad = 1;
            {retcmp}
        }} __except (1) {{
            printf("FAULT iter=%ld: the function dereferences memory this oracle cannot supply\n", iter);
            printf("tested=%lu fails=1 -> NEEDS a real-state test\n", tested);
            return 3;
        }}
        ++tested;
        if (bad) {{ if (fails < 8) printf("MISMATCH iter=%ld\n", iter); ++fails; }}
    }}
    printf("tested=%lu fails=%lu -> %s\n", tested, fails,
           fails == 0 ? "PASS (rebuild == original)" : "FAIL");
    return fails == 0 ? 0 : 1;
}}
'''


def fnv1a(data):
    h = 2166136261
    for c in data:
        h = ((h ^ c) * 16777619) & 0xFFFFFFFF
    return h


def generate(img, va, size, returns, iters, force=False):
    code = img.read(va, size)
    if len(code) != size:
        raise SystemExit(f"only {len(code)} of {size} bytes are in the file")
    attrs = classify.classify(img, va, code)
    if not attrs["self_contained"] and not force:
        raise SystemExit(f"0x{va:08X} is not self-contained (globals, calls, jumps out or x87): "
                         "compare it with build.py instead (--force to generate anyway)")
    if attrs["ptr_args"] and not force:
        raise SystemExit(f"0x{va:08X} dereferences {len(attrs['ptr_args'])} pointer argument(s): "
                         "random scalars would fault (--force to generate anyway)")
    nargs = attrs["stack_args"]
    cdecl = attrs["conv"] == "cdecl"
    stack = [f"a{i}" for i in range(nargs)]
    void = returns == "void"
    if void:
        call_o = call_r = ""
        retcmp = "/* void: compare the object only */"
    else:
        call_o, call_r = "unsigned int ro = ", "unsigned int rr = "
        retcmp = ("unsigned int ba = (unsigned int)(size_t)a, bb = (unsigned int)(size_t)b;\n"
                  "            if (ro >= ba && ro < ba + THIS_SZ && rr >= bb && rr < bb + THIS_SZ)"
                  " { if (ro - ba != rr - bb) bad = 1; }\n"
                  "            else if (ro != rr) bad = 1;")
    return TEMPLATE.format(
        va=f"{va:08X}", off=img.va_to_off(va), size=size, fnv=fnv1a(code), this_sz=0x12000,
        iters=iters, decl_ret="void" if void else "unsigned int",
        cc="__cdecl" if cdecl else "__fastcall",
        params=", ".join(([] if cdecl else ["void* ecx", "void* edx"])
                         + [f"unsigned int {x}" for x in stack]),
        args_o=", ".join(([] if cdecl else ["(void*)a", "(void*)0"]) + stack),
        args_r=", ".join(([] if cdecl else ["(void*)b", "(void*)0"]) + stack),
        argset=" ".join(f"unsigned int {x} = rnd();" for x in stack) or "/* no stack arguments */",
        call_o=call_o, call_r=call_r, retcmp=retcmp), nargs, attrs


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("va", help="function VA")
    ap.add_argument("--size", type=lambda s: int(s, 0), required=True,
                    help="the ORIGINAL function length in bytes")
    ap.add_argument("--returns", choices=("value", "void"), default="value",
                    help="compare EAX (value, default) or only the object (void)")
    ap.add_argument("--iters", type=int, default=60000, help="random cases (default 60000)")
    ap.add_argument("--exe", default=kit_paths.BASE_EXE, help="binary (default: PR2_BASE_EXE)")
    ap.add_argument("--out-dir", help="where to write (default: _build/rebuild/harness)")
    ap.add_argument("--force", action="store_true", help="generate even when not self-contained")
    ap.add_argument("--run", action="store_true", help="compile with cl 13.10 and run it")
    ap.add_argument("--source", help="your rebuild of the function (needed with --run)")
    a = ap.parse_args()

    exe = kit_paths.need(a.exe, "binary", "PR2_BASE_EXE")
    img = pe_image.Image(exe)
    va = pe_image.parse_va(a.va)
    text, nargs, attrs = generate(img, va, a.size, a.returns, a.iters, a.force)
    out = pe_image.work_dir(a.out_dir or (kit_paths.BUILD / "rebuild" / "harness"))
    h = out / f"0x{va:08X}_oracle.cpp"
    h.write_text(text, encoding="utf-8")
    print(f"wrote {h}  (convention {attrs['conv']}, {nargs} stack argument(s), returns {a.returns})", flush=True)
    if not a.run:
        return
    if not a.source:
        raise SystemExit("--run needs --source (your rebuild of the function)")
    cl, env = pe_image.vc71()
    exe_out = out / f"0x{va:08X}_oracle.exe"
    r = subprocess.run([str(cl), "/nologo", "/O2", "/EHsc", h.name, str(Path(a.source).resolve()),
                        f"/Fe{exe_out.name}", "kernel32.lib"],
                       cwd=out, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        print("BUILD FAILED:\n" + r.stdout + r.stderr)
        sys.exit(2)
    r = subprocess.run([str(exe_out), str(Path(exe).resolve())])
    sys.exit(r.returncode)


if __name__ == "__main__":
    main()
