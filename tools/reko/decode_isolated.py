#!/usr/bin/env python3
"""Decode each function alone with Reko (`decompile --data`), one C file per function.

`decompile --data <hex bytes> --base <VA>` analyses only that function's bytes: it does not
load the PE and does not follow calls, so it is fast (about 1 s per function, ~8 per second
with --jobs 8), bounded in memory, and never hits the whole-program SSA crash. All ~6000 game
functions of PR2.exe decode in about 12 minutes.

The price of isolation: with no caller present, Reko's liveness analysis sees nobody reading
eax, so functions come out typed `void` with the return value (and `this` handling) dropped;
imports show as `(*(<anonymous>**)<addr>)()` and globals as raw constants. The control flow
and the calls (`fn<VA>`) come through well: it is a readable logic view, not named source.
For returns and parameters use the whole-program decode (run_whole.py).

Writes <out>/0x<VA8>.c (default <PR2_BUILD>/reko/raw). Resumable: functions that already have
a file are skipped. Functions whose hex does not fit on a Windows command line (> ~14 KB of
code) get a stub file that says so.

    python tools/reko/decode_isolated.py --jobs 8          # every function in the list
    python tools/reko/decode_isolated.py 0x41C6F0          # specific functions
    python tools/reko/decode_isolated.py --status
"""
import argparse
import re
import shutil
import subprocess
import sys
import tempfile
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import reko_common as rc
import kit_paths

# Windows caps a command line at 32767 characters; `--data <hex>` takes 2 per byte.
MAX_HEX = 28000
BOILERPLATE = ("// image_code.c", "// Generated by", "// using Reko", '#include "image.h"')
# The function's banner (`// <VA8>: <signature>`), its definition line, then `{` and `}` with
# nothing between them.
EMPTY_BODY = re.compile(r"(?m)^// [0-9A-Fa-f]{8}: .*\n[^\n]*\n\{\s*\}")


class Image:
    """Bytes of a PE image by virtual address (read-only)."""

    def __init__(self, path: Path):
        import pefile
        self.pe = pefile.PE(str(path), fast_load=True)
        self.base = self.pe.OPTIONAL_HEADER.ImageBase

    def read(self, va: int, size: int) -> bytes:
        return self.pe.get_data(va - self.base, size)


def decode_one(decomp: Path, work: Path, va: int, code: bytes):
    """Cleaned C text, None on failure, or "OVERSIZE"."""
    hexb = code.hex()
    if len(hexb) > MAX_HEX:
        return "OVERSIZE"
    d = tempfile.mkdtemp(prefix="rk_", dir=str(work))
    try:
        # Reko wants the base address as hex WITHOUT 0x.
        subprocess.run([str(decomp), "decompile", "--arch", "x86-protected-32", "--env", "win32",
                        "--base", "%08X" % va, "--data", hexb],
                       capture_output=True, text=True, cwd=d, timeout=120)
        cpath = Path(d) / "image.reko" / "image_code.c"
        if not cpath.exists():
            return None
        lines = [ln for ln in cpath.read_text(encoding="utf-8", errors="ignore").splitlines()
                 if not ln.startswith(BOILERPLATE)]
        return "\n".join(lines).strip("\n") + "\n"
    except (subprocess.TimeoutExpired, OSError):
        return None
    finally:
        shutil.rmtree(d, ignore_errors=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 epilog="See tools/reko/README.md.")
    ap.add_argument("vas", nargs="*", help="only these functions (hex VAs; must be in the list)")
    ap.add_argument("--funcs", type=Path, default=rc.DEFAULT_FUNCS,
                    help="TSV function list with addr and size columns "
                         "(default: <PR2_BUILD>/ghidra/out/worklist.tsv from ghidra.py callgraph)")
    ap.add_argument("--classes", default=rc.DEFAULT_CLASSES,
                    help="decode rows whose class column is one of these (default: %(default)s)")
    ap.add_argument("--include-all", action="store_true", help="decode every row, ignore the class column")
    ap.add_argument("--exe", type=Path, default=None,
                    help="binary the bytes come from (default: PR2_BASE_EXE); only read")
    ap.add_argument("--out", type=Path, default=rc.RAW_DIR,
                    help="output folder (default: <PR2_BUILD>/reko/raw)")
    ap.add_argument("--work", type=Path, default=rc.WORK_DIR,
                    help="folder for throwaway per-job Reko folders (default: <PR2_BUILD>/reko/work); "
                         "keep it on a local, non-synced disk")
    ap.add_argument("--jobs", type=int, default=1, help="parallel Reko processes (8 works well)")
    ap.add_argument("--limit", type=int, default=0, help="decode at most this many")
    ap.add_argument("--force", action="store_true", help="re-decode functions that already have a file")
    ap.add_argument("--status", action="store_true", help="print counts and exit")
    args = ap.parse_args()

    tbl = rc.load_functions(args.funcs, args.classes, args.include_all)
    args.out.mkdir(parents=True, exist_ok=True)
    have = set()
    for p in args.out.glob("0x*.c"):
        try:
            have.add(int(p.stem[2:], 16))
        except ValueError:
            pass

    if args.status:
        print("functions in list : %d" % len(tbl))
        print("decoded (files)   : %d" % len(have & set(tbl)))
        print("remaining         : %d" % len(set(tbl) - have))
        return 0

    decomp = rc.decompile_exe()
    exe = kit_paths.need(args.exe or kit_paths.BASE_EXE, "binary", "PR2_BASE_EXE" if args.exe is None else "--exe")
    img = Image(exe)
    args.work.mkdir(parents=True, exist_ok=True)

    if args.vas:
        targets = []
        for v in args.vas:
            va = int(v, 16)
            if va in tbl:
                targets.append(va)
            else:
                print("0x%08X is not in %s (or filtered out by --classes); skipped" % (va, args.funcs))
    else:
        targets = sorted(tbl)
    if not args.force:
        targets = [v for v in targets if v not in have]
    if args.limit:
        targets = targets[:args.limit]
    print("targets=%d  jobs=%d  out=%s" % (len(targets), args.jobs, args.out))
    if not targets:
        print("nothing to do")
        return 0

    lock = threading.Lock()
    st = {"done": 0, "ok": 0, "empty": 0, "fail": 0, "oversize": 0}

    def work(va):
        sz = tbl[va][0]
        try:
            body = decode_one(decomp, args.work, va, img.read(va, sz))
        except Exception as e:                      # keep the sweep going; report the cause
            body = None
            print("0x%08X: %s" % (va, e), file=sys.stderr)
        path = args.out / ("0x%08X.c" % va)
        with lock:
            st["done"] += 1
            if body == "OVERSIZE":
                path.write_text("// 0x%08X: %d bytes -- too large for Reko --data (command-line limit);\n"
                                "// use the whole-program decode (run_whole.py) for it.\n" % (va, sz))
                st["oversize"] += 1
            elif body is None:
                st["fail"] += 1
            else:
                path.write_text(body, encoding="ascii", errors="replace")
                if EMPTY_BODY.search(body):
                    st["empty"] += 1               # the whole body was dead-code-eliminated
                st["ok"] += 1
            if st["done"] % 50 == 0 or st["done"] == len(targets):
                print("[%d/%d] ok=%d empty=%d oversize=%d fail=%d last=0x%08X" %
                      (st["done"], len(targets), st["ok"], st["empty"], st["oversize"], st["fail"], va),
                      flush=True)

    if args.jobs <= 1:
        for va in targets:
            work(va)
    else:
        with ThreadPoolExecutor(max_workers=args.jobs) as ex:
            list(ex.map(work, targets))

    print("done: %d decoded (%d empty-bodied), %d oversize stubs, %d failed -> %s" %
          (st["ok"], st["empty"], st["oversize"], st["fail"], args.out))
    return 1 if st["fail"] else 0


if __name__ == "__main__":
    sys.exit(main())
